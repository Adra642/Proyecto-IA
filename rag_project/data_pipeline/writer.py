"""Write cleaned documents (Markdown + YAML front matter), stats.json and SOURCES.md."""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

from core.logging_setup import get_logger
from core.models import Document

log = get_logger(__name__)

SOURCE_TITLES: dict[str, tuple[str, str]] = {
    "kaggle_derived": ("A1/A2", "Kaggle Bank Customer Churn CSV and derived analytics documents"),
    "arxiv": ("A3", "arXiv papers on churn prediction (abstract and key sections)"),
    "wikipedia": ("A4", "Wikipedia concept pages"),
    "ecb_api": ("A5", "ECB Data Portal (policy rates, inflation, bank rates)"),
    "eurlex": ("A6", "EU legal texts (EUR-Lex / Cellar)"),
    "ecb_press": ("B4", "ECB press releases (RSS feed)"),
    "bde": ("B1", "Banco de España, Portal del Cliente Bancario"),
    "eurostat": ("B2", "Eurostat API (FR, DE, ES indicators)"),
    "worldbank": ("B3", "World Bank API (FR, DE, ES indicators)"),
    "eba": ("B6", "European Banking Authority consumer-protection pages and guidelines"),
    "ecb_hfcs": ("B5", "ECB Household Finance and Consumption Survey"),
    "credit_registers": ("B7", "Credit reporting systems (CIRBE, SCHUFA, FICP)"),
    "regulators": ("B8", "Banque de France, BaFin and Bundesbank consumer pages"),
}


def render_document(doc: Document) -> str:
    """Markdown file content: YAML front matter followed by the text."""
    front = yaml.safe_dump(
        doc.metadata.model_dump(mode="json"), sort_keys=False, allow_unicode=True, width=1000
    )
    return f"---\n{front}---\n\n{doc.text.strip()}\n"


def _write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode("utf-8"))  # bytes: no newline translation on Windows


def write_documents(docs: list[Document], processed_dir: Path) -> list[Path]:
    """Write documents to ``processed_dir/<source>/<doc_id>.md``.

    Stale ``.md`` files are removed only inside source folders that produced documents in
    this run, so a failed source never wipes its previously written corpus.

    Returns:
        Paths written, sorted.
    """
    written: set[Path] = set()
    for doc in docs:
        path = processed_dir / doc.metadata.source / f"{doc.doc_id}.md"
        _write_text(path, render_document(doc))
        written.add(path)
    for source in {d.metadata.source for d in docs}:
        for old in (processed_dir / source).glob("*.md"):
            if old not in written:
                log.info("Removing stale file %s", old)
                old.unlink()
    return sorted(written)


def _json_safe(value: float) -> float | None:
    return None if isinstance(value, float) and not math.isfinite(value) else value


def write_stats(stats: dict[str, float], path: Path) -> None:
    """Write ``stats.json`` (sorted keys; NaN becomes null)."""
    safe = {k: _json_safe(v) for k, v in sorted(stats.items())}
    _write_text(path, json.dumps(safe, indent=2, ensure_ascii=False) + "\n")


def read_front_matter(path: Path) -> dict[str, Any]:
    """Parse the YAML front matter of a processed document."""
    text = path.read_text(encoding="utf-8")
    _, front, _ = text.split("---\n", 2)
    data: dict[str, Any] = yaml.safe_load(front)
    return data


def build_sources_md(processed_dir: Path) -> str:
    """Render ``SOURCES.md`` from the documents currently in ``processed_dir``."""
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for path in sorted(processed_dir.glob("*/*.md")):
        meta = read_front_matter(path)
        groups[meta["source"]].append(meta)
    lines = [
        "# Data sources\n",
        "Generated by `uv run python -m data_pipeline.run_all`; do not edit by hand.\n",
        "| Plan ID | Source | Docs | Formats | Languages | Retrieved | License | Example URL |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for source in sorted(groups, key=lambda s: SOURCE_TITLES.get(s, ("Z", s))[0]):
        metas = groups[source]
        plan_id, title = SOURCE_TITLES.get(source, ("?", source))
        licenses = sorted({str(m["license"]) for m in metas})
        row = [
            plan_id,
            title,
            str(len(metas)),
            ", ".join(sorted({m["format"] for m in metas})),
            ", ".join(sorted({m["language"] for m in metas})),
            ", ".join(sorted({str(m["retrieved_at"]) for m in metas})),
            "; ".join(licenses).replace("|", "/"),
            sorted(m["url"] for m in metas)[0],
        ]
        lines.append("| " + " | ".join(row) + " |")
    lines += [
        "",
        "Personal identifiers of the Kaggle CSV (row number, customer id, surname) are dropped "
        "before any document is created.",
        "Out of scope by team decision: CFPB complaints and Banking77.",
        "",
    ]
    return "\n".join(lines)


def write_sources_md(processed_dir: Path, path: Path) -> None:
    """Write ``data/SOURCES.md``."""
    _write_text(path, build_sources_md(processed_dir))
